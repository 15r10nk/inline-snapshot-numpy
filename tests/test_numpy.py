def test_assert_array_equal():
    actual = numpy.array([[1, 2], [3, 4]])

    assert_array_equal(actual, snapshot(numpy.array([[1, 2], [3, 4]])))
    assert_array_equal(actual, actual)

    value = snapshot(numpy.array([[1, 2], [3, 4]]))
    assert_array_equal(actual, value)
    assert_array_equal(actual, value)


def test_assertion_helpers():
    assert_allclose(numpy.array([1.0, 2.0]), snapshot(numpy.array([1.0, 2.0 + 1e-8])))
    assert_array_almost_equal(numpy.array([1.0]), snapshot(numpy.array([1.0 + 1e-8])))
    assert_array_almost_equal_nulp(numpy.array([1.0]), snapshot(numpy.array([1.0])))
    assert_array_max_ulp(numpy.array([1.0]), snapshot(numpy.array([1.0])))


def test_failure_preserves_numpy_message():
    active = state().active
    state().active = False
    try:
        with pytest.raises(AssertionError, match="Arrays are not equal"):
            assert_array_equal(numpy.array([1, 2]), numpy.array([1, 3]))
    finally:
        state().active = active


def test_failure_preserves_non_assertion_error():
    def raises_value_error(left, right):
        raise ValueError("comparison failed")

    assert_equal = _make_assert_equal(raises_value_error)
    active = state().active
    state().active = False
    try:
        with pytest.raises(ValueError, match="comparison failed"):
            assert_equal(numpy.array([1]), numpy.array([1]))
    finally:
        state().active = active


def test_numpy_external_format(tmp_path):
    format = NumpyFormat()
    path = tmp_path / "array.npy"
    changed_path = tmp_path / "changed.npy"
    expected = numpy.array([[1, 2], [3, 4]], dtype="float32")

    assert format.is_format_for(expected)
    assert format.is_format_for(Array(expected, numpy.testing.assert_array_equal))
    assert not format.is_format_for([1, 2])

    format.encode(expected, path)
    numpy.testing.assert_array_equal(format.decode(path), expected)
    assert (
        format.rich_show(path)
        == """\
shape: (2, 2)
dtype: <f4
values:
[[1., 2.],
 [3., 4.]]"""
    )

    format.encode(expected + 1, changed_path)
    array_diff = format.rich_diff(path, changed_path)
    assert isinstance(array_diff, Syntax)
    assert "-[[1., 2.]," in array_diff.code
    assert "+[[2., 3.]," in array_diff.code

    with pytest.raises(ValueError, match="Object arrays cannot be saved"):
        format.encode(numpy.array([object()], dtype=object), path)


@requires_snapshot_updates
def test_external_snapshot():
    array_file = BytesIO()
    numpy.save(array_file, numpy.array([1, 2, 3.01]), allow_pickle=False)

    Example(
        """\
from inline_snapshot import external
from inline_snapshot_numpy import assert_array_almost_equal
from numpy import array


def test_array():
    assert_array_almost_equal(array([1, 2, 3.01]), external())
"""
    ).run_inline(
        ["--inline-snapshot=create"],
        changed_files={
            ".inline-snapshot/files_using_external.txt": """\
# this file is generated by inline-snapshot and requires no manual edits (https://15r10nk.github.io/inline-snapshot/latest/external/external/#cleaning-up-old-externals)
tests/test_something.py
""",
            "tests/__inline_snapshot__/test_something/test_array/e3e70682-c209-4cac-a29f-6fbed82c07cd.npy": array_file.getvalue(),
            "tests/test_something.py": """\
from inline_snapshot import external
from inline_snapshot_numpy import assert_array_almost_equal
from numpy import array


def test_array():
    assert_array_almost_equal(
        array([1, 2, 3.01]), external("uuid:e3e70682-c209-4cac-a29f-6fbed82c07cd.npy")
    )
""",
        },
    ).run_inline()


